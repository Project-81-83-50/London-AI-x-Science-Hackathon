def read_kpi_json(path: Path, missing: str) -> dict:
    """Read a batch_kpis.py output file, mapping absent or corrupt files to clear HTTP errors."""
    if not path.is_file():
        raise HTTPException(404, f"{missing}; run batch_kpis.py to generate KPI reports")
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        raise HTTPException(500, f"{path.name} is invalid JSON") from error


